#!/usr/bin/env python3
"""Cut the scroll-scrubbed hero frames out of the Primora brand film.

Each chapter is one continuous shot of the film. Every frame of that shot is written twice:
  images/hero-sequence/desktop/NNN.webp  16:9, 1440 x 810
  images/hero-sequence/mobile/NNN.webp   9:16, 540 x 960, cropped around the chapter's focus point
and js/hero-sequence-frames.js is rewritten with the frame counts, so the page needs no fetch().

Needs ffmpeg: either on PATH, or from `pip install imageio-ffmpeg`.

    python3 tools/hero-sequence/extract_frames.py [path/to/primora.mp4]

Without a path the film is downloaded from the Joyalukkas CDN.
"""
import glob
import json
import os
import shutil
import subprocess
import sys
import tempfile
import urllib.request

from PIL import Image

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
FILM_URL = 'https://static.joyalukkas.com/media/videos/promo-banner/Primora_DESKTOP%20WEBSITE_2560X930.mp4'
SRC_W, SRC_H = 2560, 930

# start/end in seconds of the film (trimmed a frame inside each cut).
# focus: horizontal centre of the subject, as a fraction of the full film width (used for the phone crop
# and, more gently, for the desktop crop).
CHAPTERS = [
    {'id': 'forest',   'start': 0.04,  'end': 1.44,  'focus': 0.50},
    {'id': 'sketch',   'start': 40.32, 'end': 41.36, 'focus': 0.62},
    {'id': 'stones',   'start': 22.48, 'end': 23.72, 'focus': 0.50},
    {'id': 'muse',     'start': 28.70, 'end': 29.60, 'focus': 0.56},
    {'id': 'fasten',   'start': 49.16, 'end': 50.52, 'focus': 0.50},
    {'id': 'heirloom', 'start': 52.92, 'end': 54.00, 'focus': 0.52},
]

DESKTOP = (1440, 810)
MOBILE = (540, 960)
QUALITY = 72
# The film carries a Joyalukkas watermark in its top-left corner; desktop crops never start left of this.
MIN_LEFT = 520


def ffmpeg_bin():
    exe = shutil.which('ffmpeg')
    if exe:
        return exe
    try:
        import imageio_ffmpeg
        return imageio_ffmpeg.get_ffmpeg_exe()
    except ImportError:
        sys.exit('ffmpeg not found: install it, or run `pip install imageio-ffmpeg`.')


def crop_box(focus, aspect):
    w = round(SRC_H * aspect)
    left = round(focus * SRC_W - w / 2)
    lo = MIN_LEFT if aspect > 1 else 0
    left = max(lo, min(SRC_W - w, left))
    return left, 0, left + w, SRC_H


def main():
    ff = ffmpeg_bin()
    tmp = tempfile.mkdtemp(prefix='hero-seq-')
    film = sys.argv[1] if len(sys.argv) > 1 else None
    if not film:
        film = os.path.join(tmp, 'primora.mp4')
        print('Downloading the Primora film...')
        req = urllib.request.Request(FILM_URL, headers={'User-Agent': 'Mozilla/5.0'})
        with urllib.request.urlopen(req, timeout=120) as r, open(film, 'wb') as f:
            shutil.copyfileobj(r, f)

    out = os.path.join(ROOT, 'images', 'hero-sequence')
    for sub in ('desktop', 'mobile'):
        d = os.path.join(out, sub)
        os.makedirs(d, exist_ok=True)
        for old in glob.glob(os.path.join(d, '*.webp')):
            os.remove(old)

    index = 0
    manifest = []
    for ch in CHAPTERS:
        raw = os.path.join(tmp, ch['id'])
        os.makedirs(raw, exist_ok=True)
        subprocess.run([ff, '-loglevel', 'error', '-y', '-ss', str(ch['start']), '-to', str(ch['end']),
                        '-i', film, '-q:v', '2', os.path.join(raw, '%04d.jpg')], check=True)
        frames = sorted(glob.glob(os.path.join(raw, '*.jpg')))
        first = index
        for path in frames:
            im = Image.open(path).convert('RGB')
            name = '%03d.webp' % index
            # Desktop: 16:9 crop leaning gently towards the subject.
            d_focus = 0.5 + (ch['focus'] - 0.5) * 0.5
            im.crop(crop_box(d_focus, 16 / 9)).resize(DESKTOP, Image.LANCZOS) \
                .save(os.path.join(out, 'desktop', name), 'WEBP', quality=QUALITY, method=6)
            im.crop(crop_box(ch['focus'], 9 / 16)).resize(MOBILE, Image.LANCZOS) \
                .save(os.path.join(out, 'mobile', name), 'WEBP', quality=QUALITY - 2, method=6)
            index += 1
        manifest.append({'id': ch['id'], 'from': first, 'count': len(frames)})
        print(f"{ch['id']:9s} {len(frames):3d} frames")

    data = {
        'path': 'images/hero-sequence/',
        'sets': {'desktop': {'w': DESKTOP[0], 'h': DESKTOP[1]}, 'mobile': {'w': MOBILE[0], 'h': MOBILE[1]}},
        'total': index,
        'chapters': manifest,
    }
    js = ('// Generated by tools/hero-sequence/extract_frames.py. Frames are cut from the Primora brand film.\n'
          'window.JL_HERO_SEQUENCE = ' + json.dumps(data, indent=2) + ';\n')
    with open(os.path.join(ROOT, 'js', 'hero-sequence-frames.js'), 'w', encoding='utf-8') as f:
        f.write(js)
    shutil.rmtree(tmp, ignore_errors=True)
    print(f'{index} frames written to images/hero-sequence/')


if __name__ == '__main__':
    main()
